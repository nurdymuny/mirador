/// Escape score for a PBP2a mutation: normalized resistance pressure.
///
/// High ΔΔG_bind (loss of drug affinity) and low ΔΔG_fold (target remains stable)
/// → high escape score → mutation is both beneficial to the bacterium and viable.
///
/// escape_score = ΔΔG_bind / (1 + ΔΔG_fold)
pub fn pbp2a_escape_score(delta_ddg_bind: f64, delta_ddg_fold: f64) -> f64 {
    delta_ddg_bind / (1.0 + delta_ddg_fold)
}

/// A PBP2a escape eigenvalue entry from published crystallographic and biochemical data.
#[derive(Debug, Clone)]
pub struct Pbp2aEscapeEigenvalue {
    /// Mutation name (e.g. "E150K").
    pub mutation: &'static str,
    /// Escape eigenvalue λ: normalised resistance pressure on the ceftaroline manifold.
    /// λ > 1.0 means this mutation is accessible AND significantly disrupts binding.
    pub lambda: f64,
    /// PDB accession code corroborating this entry.
    pub pdb_reference: &'static str,
}

/// Ordered escape spectrum for ceftaroline vs PBP2a.
/// Source: PDB structures 4BL2 (E150K), 4BL3 (N146K), JACS 2014, AAC 2026.
/// Eigenvalues ordered λ₁ ≥ λ₂ ≥ λ₃ ≥ λ₄.
pub const PBP2A_ESCAPE_SPECTRUM: [Pbp2aEscapeEigenvalue; 4] = [
    Pbp2aEscapeEigenvalue { mutation: "E150K", lambda: 1.59, pdb_reference: "4BL2" },
    Pbp2aEscapeEigenvalue { mutation: "N146K", lambda: 1.56, pdb_reference: "4BL3" },
    Pbp2aEscapeEigenvalue { mutation: "Y446N", lambda: 1.35, pdb_reference: "implied" },
    Pbp2aEscapeEigenvalue { mutation: "E239K", lambda: 0.76, pdb_reference: "4BL4" },
];

/// The "Beyond mecA" escape manifold: rpoB mutation pathway that arises after
/// carbapenem selective pressure (AAC 2026 LIT-1).
///
/// Dimensional reduction: the primary (PBP2a) manifold and secondary (rpoB) manifold
/// are distinct Riemannian submanifolds. Carbapenem exposure collapses the geodesic
/// distance between them, enabling inter-manifold escape.
#[derive(Debug, Clone)]
pub struct CollateralEscapeManifold {
    /// Effective curvature of the secondary (rpoB) escape pathway.
    pub lambda_collateral: f64,
    /// Probability that rpoB mutation emerges given carbapenem exposure (0–1).
    pub rpo_b_mutation_risk: f64,
}

impl CollateralEscapeManifold {
    /// The collateral manifold is active when carbapenem exposure has occurred
    /// within the preceding 90 days (clinical threshold from AAC 2026).
    pub fn is_active(&self, days_since_carbapenem: Option<f64>) -> bool {
        match days_since_carbapenem {
            Some(days) => days < 90.0,
            None => false,
        }
    }
}

