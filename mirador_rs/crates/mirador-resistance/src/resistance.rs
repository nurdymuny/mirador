/// A curvature value of the therapeutic connection at a point on the target manifold.
/// By the Ambrose-Singer theorem, the Lie algebra of the holonomy group is spanned
/// by all such curvature values along loops in T.
///
/// For a 2D target conformational space (simplified), the curvature is a scalar
/// F₁₂ = ∂₁A₂ - ∂₂A₁ valued in the Lie algebra of the structure group.
#[derive(Debug, Clone, Copy)]
pub struct CurvatureValue {
    /// Curvature component F₁₂ (antisymmetric: represents "field strength").
    pub f12: f64,
}

/// A generator of the holonomy group (Ambrose-Singer).
/// Each non-zero curvature value contributes one generator.
#[derive(Debug, Clone, Copy)]
pub struct HolonomyGenerator {
    pub value: f64,
}

/// The holonomy group Hol(∇), generated by curvature values per Ambrose-Singer.
/// For an abelian connection (U(1)), the group is generated by ℝ-linear span of
/// all curvature values — this is a subgroup of U(1) ≅ ℝ/2πℤ.
#[derive(Debug, Clone)]
pub struct HolonomyGroup {
    pub generators: Vec<HolonomyGenerator>,
}

impl HolonomyGroup {
    /// Build holonomy group from curvature values (Ambrose-Singer theorem).
    /// Filters out zero curvature (identity holonomy contribution).
    pub fn from_curvature(curvatures: &[CurvatureValue]) -> Self {
        let generators = curvatures
            .iter()
            .filter(|c| c.f12.abs() > 1e-12)
            .map(|c| HolonomyGenerator { value: c.f12 })
            .collect();
        HolonomyGroup { generators }
    }

    /// Trivial holonomy group: {identity}. Occurs iff F_∇ = 0 (flat connection).
    pub fn is_trivial(&self) -> bool {
        self.generators.is_empty()
    }

    /// Number of independent resistance directions (dimension of holonomy Lie algebra).
    pub fn dimension(&self) -> usize {
        self.generators.len()
    }

    /// Compose two holonomy elements (abelian group: addition).
    pub fn compose(a: f64, b: f64) -> f64 {
        a + b
    }
}

/// An escape geodesic: the direction along which the drug's binding affinity
/// decreases fastest under target mutation — the "escape route" to resistance.
///
/// Mathematically: the eigenvector of the curvature 2-form with largest eigenvalue.
/// Direction = dominant eigenvector, rate = corresponding eigenvalue magnitude.
#[derive(Debug, Clone)]
pub struct EscapeGeodesic {
    /// The conformational perturbation direction of maximum resistance.
    pub direction: [f64; 2],
    /// Rate of affinity loss (= |dominant eigenvalue| of curvature matrix).
    pub escape_rate: f64,
}

/// Compute the dominant escape geodesic from a 2×2 symmetric curvature matrix.
/// Uses the analytic eigenvector formula for 2×2 symmetric matrices.
///
/// # Arguments
/// * `curvature` — [[a, b], [b, d]] symmetric curvature matrix
pub fn escape_geodesic(curvature: [[f64; 2]; 2]) -> EscapeGeodesic {
    let a = curvature[0][0];
    let b = curvature[0][1]; // = curvature[1][0] (symmetric)
    let d = curvature[1][1];

    // Analytic eigenvalues of [[a,b],[b,d]]:
    // λ = (trace ± sqrt(trace²/4 - det)) / 2  ... equivalently:
    // λ = (a+d)/2 ± sqrt(((a-d)/2)² + b²)
    let mean = (a + d) / 2.0;
    let half_diff = (a - d) / 2.0;
    let disc = (half_diff * half_diff + b * b).sqrt();
    let lambda1 = mean + disc;
    let lambda2 = mean - disc;

    // Pick the eigenvalue with largest absolute value (dominant escape direction)
    let lambda = if lambda1.abs() >= lambda2.abs() { lambda1 } else { lambda2 };

    // Corresponding eigenvector: (A - λI)v = 0 → v ∝ [b, λ - a]
    // (or [1, 0] / [0, 1] for degenerate case)
    let dir = if b.abs() > 1e-12 {
        let vx = b;
        let vy = lambda - a;
        let norm = (vx * vx + vy * vy).sqrt();
        [vx / norm, vy / norm]
    } else if a.abs() >= d.abs() {
        [1.0, 0.0] // dominant eigenvalue is a
    } else {
        [0.0, 1.0] // dominant eigenvalue is d
    };

    EscapeGeodesic {
        direction: dir,
        escape_rate: lambda.abs(),
    }
}

/// A predicted resistance mutation: identifies how the target can escape the drug.
#[derive(Debug, Clone)]
pub struct ResistanceMutation {
    /// Name of the mutation (e.g., "T315I" for BCR-ABL gatekeeper)
    pub name: String,
    /// Drop in binding affinity caused by this mutation (ΔΔG in kBT units)
    pub delta_affinity_kbt: f64,
    /// Corresponding holonomy shift — how the holonomy group changes
    pub holonomy_shift: f64,
    /// Destabilization of the target itself (ΔΔG_folding in kBT); large → unlikely mutation
    pub folding_penalty_kbt: f64,
}

impl ResistanceMutation {
    /// Evolutionary accessibility: mutations that destabilize the target (folding_penalty > 5 kBT)
    /// are highly disfavored and have low probability of arising clinically.
    pub fn is_evolutionarily_accessible(&self) -> bool {
        self.folding_penalty_kbt < 5.0 // ΔΔG < ~3 kcal/mol
    }
}

